def _env_map(name):
    """«CORP.LOCAL=corp.ru,SUB.CORP.LOCAL=corp.ru» → словарь."""
    pairs = (item.split("=", 1) for item in _env_list(name) if "=" in item)
    return {key.strip(): value.strip() for key, value in pairs}


